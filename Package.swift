// swift-tools-version: 6.0
import PackageDescription

// SwiftPM links through clang with --sysroot, which records the deployment
// target instead of the SDK version in LC_BUILD_VERSION; -isysroot makes clang
// read the real one. The Makefile exports SDKROOT.
let sdkVersionLinkerFlags = Context.environment["SDKROOT"].map {
    ["-Xclang-linker", "-isysroot", "-Xclang-linker", $0]
} ?? []

let package = Package(
    name: "MoleWidget",
    platforms: [.macOS(.v15)],
    products: [
        .library(name: "MoleWidgetCore", targets: ["MoleWidgetCore"]),
        .executable(name: "MoleWidget", targets: ["MoleWidget"]),
        .executable(name: "MoleWidgetExtension", targets: ["MoleWidgetExtension"]),
    ],
    dependencies: [
        .package(url: "https://github.com/sparkle-project/Sparkle", from: "2.0.0"),
    ],
    targets: [
        .target(
            name: "MoleWidgetCore",
            path: "Sources/MoleWidgetCore",
            swiftSettings: [.swiftLanguageMode(.v5)]
        ),
        .executableTarget(
            name: "MoleWidget",
            dependencies: [
                "MoleWidgetCore",
                .product(name: "Sparkle", package: "Sparkle"),
            ],
            path: "Sources/MoleWidget",
            swiftSettings: [.swiftLanguageMode(.v5)]
        ),
        .executableTarget(
            name: "MoleWidgetExtension",
            dependencies: ["MoleWidgetCore"],
            path: "Sources/MoleWidgetExtension",
            swiftSettings: [
                .swiftLanguageMode(.v5),
                // WidgetKit interface with preferredBackgroundStyle declared;
                // generated by `make spi` (see Makefile).
                .unsafeFlags(["-I", Context.packageDirectory + "/.build/spi"]),
            ],
            linkerSettings: [
                // App extensions enter through Foundation's NSExtensionMain,
                // not the Swift-generated main — chronod's ExtensionKit
                // bootstrap traps otherwise (verified against system appexes).
                .unsafeFlags(["-Xlinker", "-e", "-Xlinker", "_NSExtensionMain"] + sdkVersionLinkerFlags)
            ]
        ),
        .testTarget(
            name: "MoleWidgetCoreTests",
            dependencies: ["MoleWidgetCore"],
            path: "Tests/MoleWidgetCoreTests",
            swiftSettings: [
                .swiftLanguageMode(.v5),
                // Swift Testing in Command Line Tools ships as a separate framework
                // (these flags are harmless with a full Xcode install)
                .unsafeFlags(["-F", "/Library/Developer/CommandLineTools/Library/Developer/Frameworks"]),
            ],
            linkerSettings: [
                .unsafeFlags([
                    "-F", "/Library/Developer/CommandLineTools/Library/Developer/Frameworks",
                    "-Xlinker", "-rpath",
                    "-Xlinker", "/Library/Developer/CommandLineTools/Library/Developer/Frameworks",
                    "-Xlinker", "-rpath",
                    "-Xlinker", "/Library/Developer/CommandLineTools/Library/Developer/usr/lib",
                ])
            ]
        ),
    ]
)
